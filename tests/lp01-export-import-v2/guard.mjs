import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {powerBIExportMode} from '../../src/server/lp-powerbi-export-mode.js';
import {powerBIReleaseMode,POWERBI_RELEASE_MODE} from '../../src/server/lp-powerbi-release-config.js';
const root=new URL('../../',import.meta.url),read=p=>readFile(new URL(p,root));
const manifest=JSON.parse(await read('docs/sql-proposals/lp01-export-import-v2/manifest.json'));
for(const [path,sha] of Object.entries(manifest.artifact_sha256))assert.equal(createHash('sha256').update(await read(path)).digest('hex'),sha,path);
assert.equal(createHash('sha256').update(await read('supabase/functions/lp-powerbi/index.ts')).digest('hex'),manifest.entrypoint_sha256);
const entry=(await read('supabase/functions/lp-powerbi/index.ts')).toString();
assert(entry.includes("powerBIReleaseMode(Deno.env.get('SGP_LP_EXPORT_MODE'))"));
assert.deepEqual(powerBIExportMode(undefined),{exportProductionV2:false,exportWriterScope:null});
assert.deepEqual(powerBIExportMode('LP-EXPORT-DUAL-1'),{exportProductionV2:true,exportWriterScope:'LP-EXPORT-DUAL-1'});
assert.throws(()=>powerBIExportMode('true'));
assert.equal(POWERBI_RELEASE_MODE,'LP-EXPORT-DUAL-1');
assert.deepEqual(powerBIReleaseMode(undefined),powerBIExportMode('LP-EXPORT-DUAL-1'));
assert.deepEqual(powerBIReleaseMode('LEGACY'),powerBIExportMode(undefined));
assert.deepEqual(powerBIReleaseMode(''),powerBIExportMode(undefined));
assert.throws(()=>powerBIReleaseMode('unknown'));
assert.throws(()=>powerBIReleaseMode('true'));
assert(entry.includes("new Set(['sgp_sesion_actual','sgp_lp_operacion_importar_xlsx'])"));
const install=(await read('docs/sql-proposals/lp01-export-import-v2/01_import_adapter_REVIEW.sql')).toString();
assert(!/\bGRANT\b|CREATE\s+(?:ROLE|POLICY)|UPDATE\s+sgp_lp_operacion\.config\s+SET\s+export_production_v2/i.test(install));
assert(install.includes('export_production_v2 boolean NOT NULL DEFAULT false'));
console.log(`PASS ${Object.keys(manifest.artifact_sha256).length} adapter artifact pins; exact dual-compatible entry point, parser default LEGACY, release explicitly dual with LEGACY override; no SQL grants or activation.`);
